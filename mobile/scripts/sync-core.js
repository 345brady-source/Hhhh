/*
 * Copies the investor-portal core from the web app (../assets/js) into
 * src/core so the iOS app and the web portal compute every figure the same
 * way. Run after changing the web core: npm run sync-core
 */
const fs = require('fs');
const path = require('path');

const FILES = ['brand.js', 'tenants.js', 'data.js', 'nacha.js'];
const from = path.resolve(__dirname, '..', '..', 'assets', 'js');
const to = path.resolve(__dirname, '..', 'src', 'core');

fs.mkdirSync(to, { recursive: true });
for (const f of FILES) {
  const src = fs.readFileSync(path.join(from, f), 'utf8');
  const header = `/* Generated by scripts/sync-core.js from assets/js/${f}. Edit the web file, then run npm run sync-core. */\n`;
  fs.writeFileSync(path.join(to, f), header + src);
  console.log('synced', f);
}
