#!/usr/bin/env node
// Plan 06-30: the files the tax forms need, shipped as scripts, because the published preview (a sandboxed frame whose
// content security policy refuses every fetch()/XHR) loads scripts but cannot fetch a file.
//   assets/forms/forms-data.js           the three official forms (each pinned in taxmaps.js and assets/forms/SHA256SUMS)
//   assets/vendor/textfont/text-regular.js   the Unicode font, regular (pinned in assets/vendor/textfont/SHA256SUMS)
//   assets/vendor/textfont/text-bold.js      the Unicode font, bold
// Every source file is checked against its pins before it is written out; a file that differs stops the run.
//   node embed-data.js            write the three data files
//   node embed-data.js --verify   write nothing; check that each data file decodes to exactly its pinned source
// The last line is "EMBED DATA: PASS (files: 3)" or "EMBED DATA: FAIL - <reason>".
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..', '..', '..', '..');
const VERIFY = process.argv.includes('--verify');
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
const fail = (why) => {
  console.log(`EMBED DATA: FAIL - ${why}`);
  process.exit(1);
};
/** SHA256SUMS in dir as { file: hex }. */
function sums(dir) {
  const out = {};
  fs.readFileSync(path.join(ROOT, dir, 'SHA256SUMS'), 'utf8')
    .split('\n')
    .filter((l) => l.trim())
    .forEach((l) => {
      const m = l.match(/^([0-9a-f]{64})\s+\*?(.+)$/);
      if (m) out[m[2].trim()] = m[1];
    });
  return out;
}
/** A pinned source file's bytes, or the run stops. */
function pinned(rel, ...pins) {
  const b = fs.readFileSync(path.join(ROOT, rel));
  const h = sha(b);
  pins.forEach((p) => {
    if (!p || p !== h) fail(`${rel} does not match its pin (${h.slice(0, 12)} vs ${String(p).slice(0, 12)})`);
  });
  return b;
}
const HEAD = (what) => `/* Generated by .planning/phases/06-onboarding-forms-w-9-and-w-8-collected-in-the-investor-onboa/checks/embed-data.js from ${what} (do not edit by hand). Base64. */\n`;

// the official forms, keyed by the map's own file path (taxforms.js looks them up by map.file)
const win = { CVPortal: {} };
vm.runInContext(fs.readFileSync(path.join(ROOT, 'assets/js/taxmaps.js'), 'utf8'), vm.createContext({ window: win }), { filename: 'taxmaps.js' });
const maps = win.CVPortal.taxmaps || {};
const formSums = sums('assets/forms');
const forms = {};
Object.keys(maps).forEach((k) => {
  const m = maps[k];
  forms[m.file] = pinned(m.file, m.sha256, formSums[path.basename(m.file)]);
});
if (Object.keys(forms).length !== 3) fail(`expected the 3 forms of taxmaps.js, found ${Object.keys(forms).length}`);
const fontSums = sums('assets/vendor/textfont');
const fonts = {
  regular: pinned('assets/vendor/textfont/DejaVuSans.ttf', fontSums['DejaVuSans.ttf']),
  bold: pinned('assets/vendor/textfont/DejaVuSans-Bold.ttf', fontSums['DejaVuSans-Bold.ttf'])
};

const OUT = {
  'assets/forms/forms-data.js': {
    text:
      HEAD('the pinned official forms in assets/forms') +
      '(function (NS) {\n  NS.taxformsData = Object.assign(NS.taxformsData || {}, {\n' +
      Object.keys(forms)
        .map((f) => `    '${f}': '${forms[f].toString('base64')}'`)
        .join(',\n') +
      '\n  });\n})((window.CVPortal = window.CVPortal || {}));\n',
    expect: forms,
    read: (ns) => ns.taxformsData
  },
  'assets/vendor/textfont/text-regular.js': {
    text: HEAD('assets/vendor/textfont/DejaVuSans.ttf') + `(function (NS) {\n  NS.fontData = Object.assign(NS.fontData || {}, { regular: '${fonts.regular.toString('base64')}' });\n})((window.CVPortal = window.CVPortal || {}));\n`,
    expect: { regular: fonts.regular },
    read: (ns) => ns.fontData
  },
  'assets/vendor/textfont/text-bold.js': {
    text: HEAD('assets/vendor/textfont/DejaVuSans-Bold.ttf') + `(function (NS) {\n  NS.fontData = Object.assign(NS.fontData || {}, { bold: '${fonts.bold.toString('base64')}' });\n})((window.CVPortal = window.CVPortal || {}));\n`,
    expect: { bold: fonts.bold },
    read: (ns) => ns.fontData
  }
};

let n = 0;
for (const rel of Object.keys(OUT)) {
  const o = OUT[rel];
  if (!VERIFY) fs.writeFileSync(path.join(ROOT, rel), o.text);
  // what the browser gets: the file run as a script, each entry decoded and compared with its pinned source
  const w = { CVPortal: {} };
  vm.runInContext(fs.readFileSync(path.join(ROOT, rel), 'utf8'), vm.createContext({ window: w }), { filename: rel });
  const got = o.read(w.CVPortal) || {};
  Object.keys(o.expect).forEach((k) => {
    if (typeof got[k] !== 'string') fail(`${rel} has no entry ${k}`);
    if (!Buffer.from(got[k], 'base64').equals(o.expect[k])) fail(`${rel}: entry ${k} does not decode to its pinned source`);
  });
  if (Object.keys(got).length !== Object.keys(o.expect).length) fail(`${rel} has entries beyond its sources: ${Object.keys(got).join(', ')}`);
  console.log(`PASS ${rel} (${fs.statSync(path.join(ROOT, rel)).size} bytes): ${Object.keys(o.expect).map((k) => `${k} = ${sha(o.expect[k]).slice(0, 12)}`).join(', ')}`);
  n++;
}
console.log(`EMBED DATA: PASS (files: ${n})`);
