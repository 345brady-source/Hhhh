// make-holidays writes the independent holiday fixture of phase 16's checks (test-only; never shipped): every weekday
// of 2025-01-01..2035-12-31 that moov-io/base v0.68.3 (Apache-2.0) IsBankingDay calls closed, one 'YYYY-MM-DD' a line.
// Run from this folder: GOFLAGS=-mod=mod go run . > ../holidays-2025-2035.txt
package main

import (
	"fmt"
	"runtime"
	"time"

	"github.com/moov-io/base"
)

func main() {
	fmt.Println("# Weekday closures 2025-2035 from moov-io/base v0.68.3 IsBankingDay (Apache-2.0); generated by make-holidays; regenerate, never edit")
	fmt.Printf("# Go version: %s\n", runtime.Version())
	day := time.Date(2025, time.January, 1, 12, 0, 0, 0, time.UTC)
	end := time.Date(2035, time.December, 31, 12, 0, 0, 0, time.UTC)
	for !day.After(end) {
		wd := day.Weekday()
		if wd != time.Saturday && wd != time.Sunday && !base.NewTime(day).IsBankingDay() {
			fmt.Println(day.Format("2006-01-02"))
		}
		day = day.AddDate(0, 0, 1)
	}
}
