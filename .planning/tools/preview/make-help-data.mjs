// Writes help-data.js beside this file for the owner's preview: the server's help rules, both guides and the page list
// (server/lib/help-guide.mjs), as window.CVHelpData, read by help-preview.js. Preview only: no product page loads it.
// Usage: node .planning/tools/preview/make-help-data.mjs            writes help-data.js
//        node .planning/tools/preview/make-help-data.mjs --verify   exits 1 when help-data.js is missing or stale
// Run it (and republish the preview) after any help guide merge (server/help/guide.md -> server/lib/help-guide.mjs).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..');
const OUT = path.join(HERE, 'help-data.js');
const m = await import(pathToFileURL(path.join(ROOT, 'server', 'lib', 'help-guide.mjs')).href);

const pages = {};
for (const [k, v] of Object.entries(m.PAGES)) pages[k] = { title: v.title, audience: v.audience, where: v.where };
const data = { version: m.VERSION, marker: m.MARKER, rules: m.RULES, guide: { sponsor: m.GUIDE.sponsor, investor: m.GUIDE.investor }, pages };
const text =
  `// Generated by .planning/tools/preview/make-help-data.mjs from server/lib/help-guide.mjs (guide ${m.VERSION}). Do not edit.\n` +
  `// Preview only: the owner's preview page loads it before help-preview.js; no product page does.\n` +
  `window.CVHelpData = ${JSON.stringify(data)};\n`;

if (process.argv.includes('--verify')) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (have === text) {
    console.log(`help-data.js: current (guide ${m.VERSION})`);
  } else {
    console.log(`help-data.js: ${have === null ? 'missing' : 'STALE'} (server guide ${m.VERSION}); run node .planning/tools/preview/make-help-data.mjs`);
    process.exit(1);
  }
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(ROOT, OUT)} (guide ${m.VERSION}, ${text.length} bytes)`);
}
