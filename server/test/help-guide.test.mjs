// The help guide and its rules (phase 07): server/help/guide.md and server/help/rules.md are the only sources;
// server/lib/help-guide.mjs is generated from them by server/help/build.mjs. These tests read the portal's own
// source (assets/js) so that a page or step that is added, removed or renamed fails here until the guide follows.
// No network and no model: nothing here proves that an instruction in the guide is the right way to do a task.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, verify, parse } from '../help/build.mjs';
import { VERSION, RULES, MARKER, GUIDE, PAGES } from '../lib/help-guide.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const JS_DIR = path.join(ROOT, 'assets', 'js');
const read = (...p) => fs.readFileSync(path.join(ROOT, ...p), 'utf8');
const JS = Object.fromEntries(
  fs
    .readdirSync(JS_DIR)
    .filter((f) => f.endsWith('.js'))
    .sort()
    .map((f) => [f, fs.readFileSync(path.join(JS_DIR, f), 'utf8')])
);
const ALL_JS = Object.values(JS).join('\n');
const GUIDE_SRC = read('server', 'help', 'guide.md');
const RULES_SRC = read('server', 'help', 'rules.md');
const SRC = parse(GUIDE_SRC);

/** Every route the portal registers: { name: file }. */
const ROUTE_RE = /NS\.views(?:\.([a-zA-Z]+)|\['([a-z0-9-]+)'\])\s*=\s*\{/g;
const ROUTES = {};
for (const [file, text] of Object.entries(JS)) for (const m of text.matchAll(ROUTE_RE)) ROUTES[m[1] || m[2]] = file;

/** The keys of `const <name> = { key: 'Label', ... };` in a source text. */
function objectKeys(text, name) {
  const m = new RegExp(`const ${name} = \\{([\\s\\S]*?)\\n\\s*\\};`).exec(text);
  return m ? [...m[1].matchAll(/^\s*([a-zA-Z]+):\s*'/gm)].map((x) => x[1]) : [];
}
/** The labels of `const NAV = [ ['route', 'Label'], ... ];` in a source text. */
function navLabels(text) {
  const m = /const NAV = \[([\s\S]*?)\n\s*\];/.exec(text);
  return m ? [...m[1].matchAll(/\['[a-z-]+',\s*'([^']+)'\]/g)].map((x) => x[1]) : [];
}
const FL = objectKeys(JS['onboarding.js'], 'FL');
const LABELS = objectKeys(JS['onboarding.js'], 'LABELS');
const STEPS = [...FL.map((k) => `invite/${k}`), ...LABELS.map((k) => `onboarding/${k}`)];
const fileOf = (key) => (key.includes('/') ? 'onboarding.js' : ROUTES[key]);

/** One character of a text changed: its first character. */
const oneCharChanged = (s) => (s[0] === 'x' ? 'y' : 'x') + s.slice(1);

test('in sync: the generated module is what the generator writes from the two sources now', () => {
  const generated = read('server', 'lib', 'help-guide.mjs');
  assert.equal(generated, build(), 'server/lib/help-guide.mjs differs from its sources: run `node server/help/build.mjs`');
  assert.equal(verify().ok, true);
  const first = SRC.entries[0].text;
  assert.equal(verify({ guide: GUIDE_SRC.replace(first, oneCharChanged(first)) }).ok, false, 'a guide changed by one character must not verify');
  assert.equal(verify({ rules: oneCharChanged(RULES_SRC) }).ok, false, 'rules changed by one character must not verify');
  assert.match(generated, /^\/\/ Generated by server\/help\/build\.mjs/);
});

test('every route the portal registers has a guide entry or a skip reason', () => {
  const found = Object.keys(ROUTES);
  assert.ok(found.length >= 30, `only ${found.length} routes found in assets/js: the route pattern no longer matches the code`);
  const missing = found.filter((r) => !(r in PAGES) && !(r in SRC.skip)).sort();
  assert.deepEqual(missing, [], `routes with no entry and no skip reason in server/help/guide.md: ${missing.join(', ')}`);
  for (const [k, reason] of Object.entries(SRC.skip)) assert.ok(reason.length >= 10, `skip reason for ${k} is too short to be a reason`);
});

test('every step of the invitation flow and of the typed activation has an entry or a skip reason', () => {
  assert.ok(FL.length >= 10, `only ${FL.length} step labels found in FL (onboarding.js)`);
  assert.ok(LABELS.length >= 5, `only ${LABELS.length} step labels found in LABELS (onboarding.js)`);
  const missing = STEPS.filter((k) => !(k in PAGES) && !(k in SRC.skip));
  assert.deepEqual(missing, [], `steps with no entry and no skip reason in server/help/guide.md: ${missing.join(', ')}`);
});

test('no stale entry: every entry and every skip line names a route or step the code still has', () => {
  const known = new Set([...Object.keys(ROUTES), ...STEPS]);
  const stale = [...Object.keys(PAGES), ...Object.keys(SRC.skip)].filter((k) => !known.has(k));
  assert.deepEqual(stale, [], `entries or skip lines for routes or steps that no longer exist: ${stale.join(', ')}`);
  assert.deepEqual(Object.keys(PAGES), SRC.entries.map((e) => e.key), 'PAGES holds the entries of guide.md in source order');
});

test('names on the screens: every anchor and every quoted name in the guide is text the portal source holds', () => {
  const lost = [];
  for (const e of SRC.entries) {
    const file = fileOf(e.key);
    assert.ok(e.anchors.length >= 1, `${e.key} has no anchor`);
    for (const a of e.anchors) if (!file || !JS[file].includes(a)) lost.push(`${e.key}: anchor "${a}" is not in ${file || 'any file'}`);
    for (const m of e.text.matchAll(/"([^"\n]*)"/g)) if (!m[1] || !ALL_JS.includes(m[1])) lost.push(`${e.key}: "${m[1]}" is not in assets/js`);
    assert.equal((e.text.match(/"/g) || []).length % 2, 0, `${e.key} has an unpaired double quote`);
    assert.doesNotMatch(e.text, /[“”]/, `${e.key} uses curly double quotes: a quoted name must be in straight quotes so it is checked`);
  }
  assert.deepEqual(lost, [], `names the guide gives that the screens no longer show:\n${lost.join('\n')}`);
});

test('menu labels: every label of the sponsor menu is in the sponsor guide and of the investor menu in the investor guide', () => {
  const consoleNav = navLabels(JS['console.js']);
  const portalNav = navLabels(JS['portal.js']);
  assert.ok(consoleNav.length >= 15, `only ${consoleNav.length} labels found in console.js NAV`);
  assert.ok(portalNav.length >= 5, `only ${portalNav.length} labels found in portal.js NAV`);
  const missS = consoleNav.filter((l) => !GUIDE.sponsor.includes(l));
  const missI = portalNav.filter((l) => !GUIDE.investor.includes(l));
  assert.deepEqual(missS, [], `sponsor menu labels the sponsor guide never names: ${missS.join(', ')}`);
  assert.deepEqual(missI, [], `investor menu labels the investor guide never names: ${missI.join(', ')}`);
});

test('white label and sizes: no vendor, model or product name, no forbidden word, no email address, and the byte limits hold', () => {
  // server/test/read.test.mjs VENDOR, widened with two more model names as whole words.
  const VENDOR = /anthropic|claude|\bopus\b|sonnet|haiku|\bfable\b|\bmythos\b/i;
  // Copies of VENDORS, VENDOR_RE and WORD_RE of the phase 06 browser checks (checks/lib.js), kept the same as there.
  const VENDORS = /pdf-lib|pdf\.js|Carrow|\bVale\b|DocuSign|SignNow|Adobe|HelloSign|Dropbox|PandaDoc|Powered by/i;
  const VENDOR_RE = /onnx|onnxruntime|microsoft|pytorch|torch|scikit|sklearn|anthropic|claude|\bopus\b|\bsonnet\b|\bhaiku\b/i;
  const WORD_RE = /\bbasic(s|ally)?\b/i;
  const EMAIL = /[A-Z0-9._%+-]+@[A-Z0-9-]+(\.[A-Z0-9-]+)+/i;
  const product = (/product:\s*'([^']+)'/.exec(JS['edition.js']) || [])[1];
  assert.ok(product && product.length >= 3, 'the product name was not found in assets/js/edition.js');
  const hit = (text, re) => text.split('\n').filter((l) => re.test(l)).map((l) => l.trim().slice(0, 120));
  for (const [name, text] of [['sponsor guide', GUIDE.sponsor], ['investor guide', GUIDE.investor], ['rules', RULES]]) {
    for (const re of [VENDOR, VENDORS, VENDOR_RE, EMAIL]) assert.deepEqual(hit(text, re), [], `${name} matches ${re}`);
  }
  for (const [name, text] of [['sponsor guide', GUIDE.sponsor], ['investor guide', GUIDE.investor]]) {
    assert.deepEqual(hit(text, WORD_RE), [], `${name} uses the forbidden word`);
    assert.ok(!text.toLowerCase().includes(product.toLowerCase()), `${name} contains the product's name`);
    // The help route's output guard is applied to every line of a guide by plan 07-02: no line it would refuse.
    const long = text.split('\n').filter((l) => l.length > 1000).map((l) => l.slice(0, 80));
    assert.deepEqual(long, [], `${name} has a line longer than 1,000 characters`);
    assert.deepEqual(hit(text, /\d{8,}|\b\d{3}[- ]?\d{2}[- ]?\d{4}\b|\b\d{2}-\d{7}\b/), [], `${name} has a long number or a tax-number shape`);
  }
  const bytes = (s) => Buffer.byteLength(s, 'utf8');
  assert.ok(bytes(GUIDE.sponsor) <= 48000, `sponsor guide is ${bytes(GUIDE.sponsor)} bytes (limit 48,000)`);
  assert.ok(bytes(GUIDE.investor) <= 20000, `investor guide is ${bytes(GUIDE.investor)} bytes (limit 20,000)`);
  assert.ok(bytes(RULES) <= 6000, `rules are ${bytes(RULES)} bytes (limit 6,000)`);
  for (const a of ['sponsor', 'investor']) {
    assert.ok(bytes(RULES) + bytes(GUIDE[a]) >= 4096, `rules plus the ${a} guide are ${bytes(RULES) + bytes(GUIDE[a])} bytes: too short to be cached (4,096)`);
  }
});

test('audiences: the investor guide holds investor pages only, and the exports have the agreed shape', () => {
  assert.deepEqual(Object.keys(GUIDE), ['sponsor', 'investor']);
  assert.ok(Object.isFrozen(GUIDE) && Object.isFrozen(PAGES));
  assert.ok(GUIDE.sponsor.startsWith('<guide audience="sponsor">\n') && GUIDE.sponsor.endsWith('\n</guide>'));
  assert.ok(GUIDE.investor.startsWith('<guide audience="investor">\n') && GUIDE.investor.endsWith('\n</guide>'));
  assert.ok(SRC.entries.some((e) => e.audience === 'sponsor') && SRC.entries.some((e) => e.audience !== 'sponsor'), 'the guide has entries for both audiences');
  for (const e of SRC.entries) {
    const p = PAGES[e.key];
    assert.ok(p && typeof p.title === 'string' && p.title.length > 0, `${e.key} has no title`);
    assert.ok(['sponsor', 'investor', 'both'].includes(p.audience), `${e.key} has audience ${p.audience}`);
    assert.ok(typeof p.where === 'string' && p.where.includes(`"${p.title}"`), `${e.key} has no where phrase`);
    assert.deepEqual(Object.keys(p), ['title', 'audience', 'where']);
    assert.ok(e.text.length >= 40, `${e.key} has no text`);
    assert.ok(GUIDE.sponsor.includes(e.text), `the sponsor guide lacks the text of ${e.key}`);
    assert.equal(GUIDE.investor.includes(e.text), e.audience !== 'sponsor', `${e.key} (${e.audience}) is ${e.audience === 'sponsor' ? 'in' : 'missing from'} the investor guide`);
    if (e.audience === 'sponsor') assert.ok(!GUIDE.investor.includes(`${p.where}\n`), `the investor guide names ${p.where}`);
  }
  assert.doesNotMatch(GUIDE.investor, /\bconsole\b/i, 'the investor guide speaks of the console');
  assert.ok(MARKER.length >= 16 && /^[a-z0-9-]+$/.test(MARKER), 'the marker is 16 or more lowercase letters, digits and hyphens');
  assert.equal(RULES.split(MARKER).length - 1, 1, 'the marker occurs exactly once in the rules');
  assert.ok(!GUIDE.sponsor.includes(MARKER) && !GUIDE.investor.includes(MARKER), 'the marker is in a guide');
  assert.equal(RULES, RULES_SRC.trim());
  assert.match(VERSION, /^[0-9a-f]{12}$/);
});
